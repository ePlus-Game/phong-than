def tcvn(s):
    o = bytearray()
    for ch in unicodedata.normalize("NFC", s):
        if ord(ch) < 128: o.append(ord(ch))
        elif ch in _low: o.append(_low[ch])
        elif ch.lower() in _low: o.append(_low[ch.lower()])
        else: raise ValueError(repr(ch))
    return bytes(o)


def lit(b):
    s = ""
    for c in b:
        if c == 92: s += "\\\\"
        elif c == 34: s += "\\\""
        elif 32 <= c < 127: s += chr(c)
        else: s += "\\%d" % c
    return '"' + s + '"'


def gbk(path):
    return lit(path.encode("gbk"))


def T(s):
    """TCVN3 string literal (escaped, file stays ASCII)."""
    return lit(tcvn(s))


def expand(src):
    # «...» -> TCVN3 literal ; ‹path› -> GBK path literal
    src = re.sub(r"«(.*?)»", lambda m: T(m.group(1)), src, flags=re.S)
    src = re.sub(r"‹(.*?)›", lambda m: gbk(m.group(1)), src, flags=re.S)
    # Chinese names left in comments: GBK hex so the file stays ASCII
    src = "".join(c if ord(c) < 128 else "<%s>" % c.encode("gbk").hex() for c in src)
    return src


