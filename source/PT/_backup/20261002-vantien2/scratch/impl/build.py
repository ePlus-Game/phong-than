# Build the Van Tien tran Lua files (2026-10-02, agent vantien).
#  - src\*.lua are UTF-8; every non-ASCII char is converted to TCVN3 and written as a \ddd escape,
#    so the output files are pure ASCII (safe for later edits) and show TCVN3 text in game.
#  - vt_data.lua is generated here from Region_S data: every NPC / teleport cell is checked to be
#    free (obstacle 0) and in the right connected area of the Huyen map.
#  - mission/timer wrappers are generated.
# Output: out\script\... (same layout as Server\script).
