def plan(n):
    g = Grid("万仙阵-幻（%s）" % EL[n - 1])
    v = VNG[n]
    used = set()
    def pick(p, comp, r=12):
        for rr in range(0, r + 1):
            for dx in range(-rr, rr + 1):
                for dy in range(-rr, rr + 1):
                    q = (p[0] + dx, p[1] + dy)
                    if g.free(q) and q in comp and q not in used:
                        used.add(q); return q
        raise RuntimeError("no free cell near %s" % (p,))
    entry0 = g.nearest_free(v["entry"], rmax=4)
    main = g.comp(entry0)
    entry = pick(v["entry"], main)
    ttc = g.comp(g.nearest_free(v["tt"], rmax=2))
    assert v["tt"] not in main or n == 0, "TT zone must be isolated"
    dest = v["tt"]                       # trap destination (VNG SetPos), players arrive here
    used.add(dest)
    tt = pick((dest[0] + 5, dest[1] + 6), ttc)   # Thong Thien a few cells away from the arrival cell
    z2 = g.nearest_free(v["zone2"], rmax=2)
    z2c = g.comp(z2)
    doctors = [pick((entry[0] + 3, entry[1] + 3), main), pick((dest[0] - 3, dest[1] + 3), ttc)]
    if z2 not in main:
        doctors.append(pick((z2[0] + 3, z2[1] + 3), z2c))
    chests = [pick((tt[0] + dx, tt[1] + dy), ttc) for dx, dy in ((4, 0), (-4, 0), (0, 5), (0, -5))]
    tien = [pick(p, main) for p in v["tien"]]
    mobs = []
    for (x, y) in tien:
        for k, (dx, dy) in enumerate(((6, 0), (-6, 0), (0, 7))):
            mobs.append(pick((x + dx, y + dy), main) + (MOBTPL[n][k % 2],))
    # trap cells of the map must be in the main area (walkable)
    traps = sorted(set(g.trap.values()))
    for p, t in g.trap.items():
        q = g.nearest_free(p, rmax=1)
        assert q in main, "trap outside main area"
    return dict(entry=entry, tt=tt, doctors=doctors, chests=chests, tien=tien, mobs=mobs, traps=traps,
                ttzone=len(ttc), mainzone=len(main))

def lua_pt(p): return "{%d,%d}" % (p[0], p[1])
def lua_list(ps): return "{" + ",".join(lua_pt(p) for p in ps) + "}"

