from tcvn import low as _low
from mapgrid import Grid

def tcvn(s):
    o = bytearray()
    for ch in unicodedata.normalize("NFC", s):
        if ord(ch) < 128: o.append(ord(ch))
        elif ch in _low: o.append(_low[ch])
        elif ch.lower() in _low: o.append(_low[ch.lower()])
        else: raise ValueError(repr(ch))
    return bytes(o)

def esc_bytes(b):
    out = []
    for c in b:
        out.append("\\%03d" % c if c >= 128 else chr(c))
    return "".join(out)

def esc_text(s):  # UTF-8 source text -> ASCII Lua with TCVN3 escapes
    return esc_bytes(tcvn(s))

OUT = os.path.join(HERE, "out", "script")
def write(rel, text):
    p = os.path.join(OUT, rel)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    data = text.replace("\r\n", "\n").replace("\n", "\r\n").encode("ascii")
    open(p, "wb").write(data)
    return p

