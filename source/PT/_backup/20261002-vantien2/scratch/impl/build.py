    src = os.path.join(HERE, "src")
    for r, _, fs in os.walk(src):
        for f in fs:
            if not f.endswith(".lua"): continue
            full = os.path.join(r, f)
            rel = os.path.relpath(full, src)
            text = open(full, encoding="utf-8").read()
            write(rel, esc_text(text))
